const { Schema, model } = require("mongoose");

const timeEntrySchema = new Schema(
  {
    owner: { type: Schema.Types.ObjectId, ref: "User", required: true },
    task: { type: Schema.Types.ObjectId, ref: "Task", required: true },
    description: { type: String, trim: true, maxlength: 200, default: "" },
    startTime: { type: Date, required: true },                 // generated by the server
    endTime: { type: Date, default: null },
    duration: { type: Number, min: 0, default: 0 },            // seconds
    isRunning: { type: Boolean, default: false },
    reminderCount: { type: Number, default: 0 }                // "still running?" e-mails already sent for this timer
  },
  { timestamps: true }
);

timeEntrySchema.index({ owner: 1, startTime: -1 });
timeEntrySchema.index({ task: 1 });
// The database guarantees at most ONE running timer per user, even with concurrent requests.
timeEntrySchema.index({ owner: 1 }, { unique: true, partialFilterExpression: { isRunning: true }, name: "one_running_timer_per_user" });

timeEntrySchema.set("toJSON", { transform: (doc, ret) => { delete ret.__v; delete ret.reminderCount; return ret; } });

module.exports = model("TimeEntry", timeEntrySchema);
